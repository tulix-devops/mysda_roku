<#
.SYNOPSIS
  Generates source/ScMetrics.brs: the advance width of every printable ASCII
  character in the Plus Jakarta Sans faces the C - Showcase design measures,
  so it can size a pill button, chip or badge to its text.

.DESCRIPTION
  Ported from wpa_live_roku/tools/build-metrics.ps1. SceneGraph's Font node
  has no measuring API, and Label.boundingRect() is 0 until the node is laid
  out - exactly when a pill needs its width
  (knowledge/dev-roku/text-measurement-and-label-height).

  Measures the shipped TTFs with GDI+ at 100 px, one character at a time,
  typographic (no padding):
    PlusJakartaSans-ExtraBold   focused buttons, titles   ScJakartaXBAdvances
    PlusJakartaSans-Bold        buttons, chips            ScJakartaBoldAdvances
    PlusJakartaSans-SemiBold    meta, badges              ScJakartaSemiAdvances
  ScTextW sums them. Kerning is not modelled, so measured labels are also
  centred: any residual error splits evenly on both sides.

  Re-run when a font file changes. Output is deterministic.
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$root = Split-Path $PSScriptRoot -Parent
$out = Join-Path $root 'source\ScMetrics.brs'

function Measure-Advances([string]$ttfName) {
    $ttf = Join-Path $root ('images\fonts\' + $ttfName)
    $pf = New-Object System.Drawing.Text.PrivateFontCollection
    $pf.AddFontFile($ttf)
    $fam = $pf.Families[0]
    # Bold ONLY for a *-Bold.ttf file: GDI+ synthesises a bold for a
    # single-weight family otherwise, ~3.5% wide (greaterlove_roku, 2026-10-02).
    $style = [System.Drawing.FontStyle]::Regular
    if ($ttfName -like '*-Bold.ttf' -and $fam.IsStyleAvailable([System.Drawing.FontStyle]::Bold)) {
        $style = [System.Drawing.FontStyle]::Bold
    }
    $font = New-Object System.Drawing.Font($fam, 100, $style, [System.Drawing.GraphicsUnit]::Pixel)
    $bmp = New-Object System.Drawing.Bitmap(10, 10)
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::AntiAlias
    $fmt = [System.Drawing.StringFormat]::GenericTypographic
    $fmt.FormatFlags = $fmt.FormatFlags -bor [System.Drawing.StringFormatFlags]::MeasureTrailingSpaces

    # Advance of c = width("Hc") - width("H").
    $base = $g.MeasureString('H', $font, 10000, $fmt).Width
    $w = @()
    for ($c = 32; $c -le 126; $c++) {
        $pair = $g.MeasureString('H' + [char]$c, $font, 10000, $fmt).Width
        $w += [int][math]::Round(($pair - $base) * 10)   # tenths of a px at 100 px
    }
    $g.Dispose(); $bmp.Dispose(); $font.Dispose(); $pf.Dispose()
    Write-Host ("  {0} ({1}): 'W' = {2}, 'i' = {3}, space = {4} tenths at 100px" -f $ttfName, $fam.Name, $w[87 - 32], $w[105 - 32], $w[0])
    return ,$w
}

function Format-Table($w) {
    $rows = @()
    for ($i = 0; $i -lt $w.Count; $i += 16) {
        $rows += '        ' + (($w[$i..([math]::Min($i + 15, $w.Count - 1))]) -join ', ')
    }
    return ($rows -join (",`r`n"))
}

$fonts = @(
    @{ ttf = 'PlusJakartaSans-ExtraBold.ttf'; fn = 'ScJakartaXBAdvances';   cache = 'scAdvXB' },
    @{ ttf = 'PlusJakartaSans-Bold.ttf';      fn = 'ScJakartaBoldAdvances'; cache = 'scAdvBold' },
    @{ ttf = 'PlusJakartaSans-SemiBold.ttf';  fn = 'ScJakartaSemiAdvances'; cache = 'scAdvSemi' }
)

$body = ''
foreach ($f in $fonts) {
    $table = Format-Table (Measure-Advances $f.ttf)
    $body += @"

' $($f.ttf -replace '\.ttf$', '') - images/fonts/$($f.ttf)
function $($f.fn)() as object
    if m.$($f.cache) <> invalid then return m.$($f.cache)
    m.$($f.cache) = [
$table
    ]
    return m.$($f.cache)
end function

"@
}

$src = @"
' ============================================================================
' ScMetrics.brs - GENERATED by tools/build-sc-metrics.ps1. Do not edit by hand.
'
' Advances for printable ASCII (32..126), in tenths of a pixel at a 100 px
' font, measured from the shipped TTFs. ScTextW sums them.
' ============================================================================
$body
"@
[IO.File]::WriteAllText($out, $src.TrimEnd() + "`r`n", (New-Object System.Text.UTF8Encoding $false))
Write-Host ("metrics -> {0} ({1} fonts)" -f $out, $fonts.Count)
